// Command gen writes the AWS read add-on that stackdna permissions puts in
// the capture role: the reads the registry schemas name that AWS's
// ReadOnlyAccess does not grant. Run it through scripts/gen-aws-reads.sh,
// which fetches the current ReadOnlyAccess first.
//
//	go run ./internal/onboard/awsreads/gen --readonly-policy ro.json --version v190 --regions us-east-1,us-east-2
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/stackdna/core/internal/awscc"
	"github.com/stackdna/core/internal/onboard/awsreads"
)

func main() {
	policy := flag.String("readonly-policy", "", "ReadOnlyAccess's policy document (JSON)")
	version := flag.String("version", "", "ReadOnlyAccess's version ID, recorded in the output")
	regions := flag.String("regions", "us-east-1,us-east-2", "registries to take types from (their union)")
	out := flag.String("out", "internal/onboard/templates/aws-read-addon.json", "file to write")
	flag.Parse()
	if *policy == "" || *version == "" {
		fmt.Fprintln(os.Stderr, "gen: --readonly-policy and --version are required")
		os.Exit(1)
	}
	b, err := os.ReadFile(*policy)
	if err != nil {
		fail(err)
	}
	base, err := awsreads.ParsePolicy(b)
	if err != nil {
		fail(err)
	}
	cache, err := os.UserCacheDir()
	if err != nil {
		fail(err)
	}
	var regs []*awscc.Registry
	var digests []string
	for _, r := range strings.Split(*regions, ",") {
		reg, err := awscc.LoadBundle(strings.TrimSpace(r), filepath.Join(cache, "stackdna", "aws"), 24*time.Hour)
		if err != nil {
			fail(err)
		}
		regs = append(regs, reg)
		digests = append(digests, r+"="+reg.Digest)
	}
	res, err := awsreads.Compute(regs, base)
	if err != nil {
		fail(err)
	}
	doc := map[string]any{
		"note":             "Generated by scripts/gen-aws-reads.sh; do not edit. Reads the CloudFormation registry's list and read handlers need that ReadOnlyAccess does not grant, kept to reads of configuration.",
		"readOnlyAccess":   *version,
		"registries":       digests,
		"generated":        time.Now().UTC().Format("2006-01-02"),
		"chunks":           awsreads.Chunks(res.Actions),
		"typesCompleted":   res.Completed,
		"typesStillShort":  res.Short,
		"actionCount":      len(res.Actions),
		"typesCompletedN":  len(res.Completed),
		"typesStillShortN": len(res.Short),
	}
	j, _ := json.MarshalIndent(doc, "", " ")
	if err := os.WriteFile(*out, append(j, '\n'), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("%d reads in %d policies; %d types completed, %d still short\n", len(res.Actions), len(awsreads.Chunks(res.Actions)), len(res.Completed), len(res.Short))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
