// Command gen writes the AWS read add-on that stackdna permissions puts in
// the capture role: the reads the registry schemas name that AWS's
// ReadOnlyAccess does not grant, judged by AWS's Service Reference. Every
// source is public, so it needs no AWS credentials.
//
//	go run ./internal/onboard/awsreads/gen
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"time"

	"github.com/stackdna/core/internal/awscc"
	"github.com/stackdna/core/internal/onboard/awsreads"
)

func main() {
	policy := flag.String("readonly-policy", "", "a ReadOnlyAccess document to use instead of AWS's page (with --version)")
	version := flag.String("version", "", "its version ID")
	regions := flag.String("regions", "us-east-1,us-east-2", "registries to take types from (their union)")
	out := flag.String("out", "internal/onboard/templates/aws-read-addon.json", "file to write")
	flag.Parse()

	var doc []byte
	var err error
	ver := *version
	if *policy != "" {
		if ver == "" {
			fail(fmt.Errorf("--readonly-policy needs --version"))
		}
		doc, err = os.ReadFile(*policy)
	} else {
		doc, ver, err = awsreads.FetchReadOnlyAccess()
	}
	if err != nil {
		fail(err)
	}
	base, err := awsreads.ParsePolicy(doc)
	if err != nil {
		fail(err)
	}
	cache, err := os.UserCacheDir()
	if err != nil {
		fail(err)
	}
	var regs []*awscc.Registry
	var digests []string
	for _, r := range strings.Split(*regions, ",") {
		r = strings.TrimSpace(r)
		// Fresh, not a day-old cache: this decides what a role is given.
		reg, err := awscc.LoadBundle(r, filepath.Join(cache, "stackdna", "aws"), time.Minute)
		if err != nil {
			fail(err)
		}
		regs = append(regs, reg)
		digests = append(digests, r+"="+reg.Digest)
	}
	missing, err := awsreads.Missing(regs, base)
	if err != nil {
		fail(err)
	}
	ref, err := awsreads.FetchReference(awsreads.Prefixes(missing))
	if err != nil {
		fail(err)
	}
	res := awsreads.Decide(missing, ref)
	chunks := awsreads.Chunks(res.Actions)
	// What the role is given, and what is still short. The registries'
	// digests change most weeks with nothing a role would notice; the
	// scheduled job would open a pull request for each of those.
	if old, err := os.ReadFile(*out); err == nil {
		var prev struct {
			ReadOnlyAccess string                       `json:"readOnlyAccess"`
			Chunks         [][]string                   `json:"chunks"`
			Short          map[string]map[string]string `json:"typesStillShort"`
		}
		if json.Unmarshal(old, &prev) == nil && prev.ReadOnlyAccess == ver && reflect.DeepEqual(prev.Chunks, chunks) && reflect.DeepEqual(prev.Short, res.Short) {
			fmt.Printf("unchanged: ReadOnlyAccess %s, %d reads\n", ver, len(res.Actions))
			return
		}
	}
	// The note and sources only: no date, so an unchanged result writes an
	// unchanged file and the weekly job opens no pull request.
	j, _ := json.MarshalIndent(map[string]any{
		"note":             "Generated by go run ./internal/onboard/awsreads/gen; do not edit. Reads the CloudFormation registry's list and read handlers need that ReadOnlyAccess does not grant: kept only when named as a read and not marked by AWS's Service Reference as a write or data plane; no secrets, wildcards expanded to concrete actions.",
		"readOnlyAccess":   ver,
		"registries":       digests,
		"chunks":           chunks,
		"actionCount":      len(res.Actions),
		"unverifiedByAWS":  res.Unverified,
		"typesCompleted":   res.Completed,
		"typesStillShort":  res.Short,
		"typesCompletedN":  len(res.Completed),
		"typesStillShortN": len(res.Short),
	}, "", " ")
	if err := os.WriteFile(*out, append(j, '\n'), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("ReadOnlyAccess %s: %d reads in %d policies (%d kept by name only); %d types completed, %d still short\n",
		ver, len(res.Actions), len(chunks), len(res.Unverified), len(res.Completed), len(res.Short))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
