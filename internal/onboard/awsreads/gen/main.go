// Command gen writes the AWS read add-on that truthform permissions puts in
// the capture role: the reads the registry schemas name that AWS's
// ReadOnlyAccess does not grant, judged by AWS's Service Reference. Every
// source is public, so it needs no AWS credentials.
//
//	go run ./internal/onboard/awsreads/gen
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"time"

	"github.com/usetruthform/core/internal/awscc"
	"github.com/usetruthform/core/internal/onboard/awsreads"
)

func main() {
	policy := flag.String("readonly-policy", "", "a ReadOnlyAccess document to use instead of AWS's page (with --version)")
	version := flag.String("version", "", "its version ID")
	regions := flag.String("regions", "us-east-1,us-east-2", "registries to take types from (their union)")
	out := flag.String("out", "internal/onboard/templates/aws-read-addon.json", "file to write")
	flag.Parse()

	var doc []byte
	var err error
	ver := *version
	if *policy != "" {
		if ver == "" {
			fail(fmt.Errorf("--readonly-policy needs --version"))
		}
		doc, err = os.ReadFile(*policy)
	} else {
		doc, ver, err = awsreads.FetchReadOnlyAccess()
	}
	if err != nil {
		fail(err)
	}
	base, err := awsreads.ParsePolicy(doc)
	if err != nil {
		fail(err)
	}
	cache, err := os.UserCacheDir()
	if err != nil {
		fail(err)
	}
	var regs []*awscc.Registry
	var digests []string
	for _, r := range strings.Split(*regions, ",") {
		r = strings.TrimSpace(r)
		// Fresh, not a day-old cache: this decides what a role is given.
		reg, err := awscc.LoadBundle(r, filepath.Join(cache, "truthform", "aws"), time.Minute)
		if err != nil {
			fail(err)
		}
		regs = append(regs, reg)
		digests = append(digests, r+"="+reg.Digest)
	}
	missing, err := awsreads.Missing(regs, base)
	if err != nil {
		fail(err)
	}
	ref, err := awsreads.FetchReference(awsreads.Prefixes(missing))
	if err != nil {
		fail(err)
	}
	if err := awsreads.FetchSecretFields(ref, awsreads.Candidates(missing, ref)); err != nil {
		fail(err)
	}
	res := awsreads.Decide(missing, ref, base)
	chunks := awsreads.Chunks(res.Actions)
	result := map[string]any{
		"note":                    "Generated by go run ./internal/onboard/awsreads/gen; do not edit. The reads the CloudFormation registry's list and read handlers need that ReadOnlyAccess does not grant, each kept only when named as a read, not named like a secret or data read, not denied, not marked by AWS's Service Reference as data plane or a write, and with no output field AWS marks sensitive that is named like a secret. Wildcards are expanded to concrete actions. unverified and omittedByReadOnlyAccess are kept, and listed for review.",
		"readOnlyAccess":          ver,
		"chunks":                  chunks,
		"actionCount":             len(res.Actions),
		"unverified":              res.Unverified,
		"omittedByReadOnlyAccess": res.OmittedByReadOnlyAccess,
		"typesCompleted":          res.Completed,
		"typesStillShort":         res.Short,
		"typesCompletedN":         len(res.Completed),
		"typesStillShortN":        len(res.Short),
	}
	// Everything but the registries' digests: they change most weeks with
	// nothing a role would notice, and the scheduled job would open a pull
	// request for each. Anything else that changed is written, so a source
	// that stops vouching for an action shows in the diff (a first version
	// compared only the policies and the shortfall, and would have hidden
	// that, review of #24).
	if old, err := os.ReadFile(*out); err == nil {
		var prev map[string]any
		cur, _ := json.Marshal(result)
		var now map[string]any
		_ = json.Unmarshal(cur, &now)
		if json.Unmarshal(old, &prev) == nil {
			delete(prev, "registries")
			if reflect.DeepEqual(prev, now) {
				fmt.Printf("unchanged: ReadOnlyAccess %s, %d reads\n", ver, len(res.Actions))
				return
			}
		}
	}
	result["registries"] = digests
	j, _ := json.MarshalIndent(result, "", " ")
	if err := os.WriteFile(*out, append(j, '\n'), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("ReadOnlyAccess %s: %d reads in %d policies (%d unverified, %d left out by ReadOnlyAccess); %d types completed, %d still short\n",
		ver, len(res.Actions), len(chunks), len(res.Unverified), len(res.OmittedByReadOnlyAccess), len(res.Completed), len(res.Short))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
